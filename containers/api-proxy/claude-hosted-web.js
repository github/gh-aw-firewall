'use strict';

/**
 * Claude hosted-web policy enforcement for the AWF API proxy.
 *
 * Anthropic's hosted server tools (`web_search_YYYYMMDD`, `web_fetch_YYYYMMDD`)
 * are executed by Anthropic infrastructure, not by the agent container. Squid
 * therefore only ever observes the Anthropic API endpoint — never the domain
 * that was searched or fetched — and the retrieved content returns inside an
 * already-allowed API response. The trusted api-proxy sidecar closes that
 * semantic egress gap by injecting and enforcing an AWF-configured domain
 * policy on every matching tool definition before the request is dispatched
 * upstream.
 *
 * Policy source: `AWF_CLAUDE_HOSTED_WEB_POLICY`, a JSON document generated by
 * AWF from already-validated configuration (`apiProxy.hostedWeb.claude`). It is
 * never accepted from the agent.
 *
 *   { "enabled": true, "mode": "allow"|"block", "domains": [...], "maxUses": 5 }
 *
 * Enforcement rules (see docs/awf-config-spec.md §9.9):
 *   1. `enabled: false` rejects any request containing a matching hosted tool.
 *   2. Allowlist mode: inject when the request omits `allowed_domains`,
 *      otherwise intersect; an empty intersection is rejected; a request
 *      carrying `blocked_domains` is rejected (Anthropic cannot represent both).
 *   3. Blocklist mode: inject when the request omits `blocked_domains`,
 *      otherwise union; a request carrying `allowed_domains` is rejected.
 *   4. A request carrying both filters is rejected.
 *   5. `max_uses` is clamped to `min(configured, requested)`.
 *
 * Every failure path is fail-closed: the request is rejected with a structured
 * error instead of silently stripping a tool or forwarding an unprotected one.
 * Error payloads never include prompts, queries, URLs, or request bodies.
 */

/** Versioned hosted web tool types, e.g. `web_search_20250305`, `web_fetch_20250910`. */
const HOSTED_WEB_TOOL_PATTERN = /^web_(search|fetch)_(\d{4})(\d{2})(\d{2})$/;

/**
 * Anything that looks like a hosted web tool. Values matching this prefix but
 * not {@link HOSTED_WEB_TOOL_PATTERN} are treated as unrecognized hosted tools
 * and rejected, so a future or malformed shape can never bypass the policy.
 */
const HOSTED_WEB_TOOL_PREFIX = /^web_(search|fetch)(_|$)/;

/** Lowercase DNS label characters (validated label-by-label; see isValidDomain). */
const LABEL_CHARS = /^[a-z0-9-]+$/;
const DIGITS_ONLY = /^\d+$/;
const MAX_DOMAIN_LENGTH = 253;
const MAX_LABEL_LENGTH = 63;

/**
 * Error thrown when a request violates the configured hosted-web policy.
 * `statusCode` and `code` are surfaced verbatim by proxy-request.js.
 */
class ClaudeHostedWebPolicyError extends Error {
  constructor(code, message, statusCode = 403) {
    super(message);
    this.name = 'ClaudeHostedWebPolicyError';
    this.code = code;
    this.statusCode = statusCode;
  }
}

/**
 * Returns true when `type` is a syntactically valid versioned hosted web tool.
 *
 * @param {unknown} type
 * @returns {boolean}
 */
function isHostedWebToolType(type) {
  if (typeof type !== 'string') return false;
  const match = HOSTED_WEB_TOOL_PATTERN.exec(type);
  if (!match) return false;
  const month = Number(match[3]);
  const day = Number(match[4]);
  return month >= 1 && month <= 12 && day >= 1 && day <= 31;
}

/**
 * Returns true when `type` claims to be a hosted web tool, regardless of
 * whether its version suffix is well-formed.
 *
 * @param {unknown} type
 * @returns {boolean}
 */
function isHostedWebToolCandidate(type) {
  return typeof type === 'string' && HOSTED_WEB_TOOL_PREFIX.test(type);
}

/**
 * Same syntax as the AWF config schema: a lowercase DNS hostname with at least
 * two labels, no scheme/port/path/wildcard and no raw IPv4 address. Checked
 * label-by-label rather than with one nested-quantifier regex so untrusted,
 * request-supplied values cannot trigger catastrophic backtracking.
 *
 * @param {unknown} value
 * @returns {boolean}
 */
function isValidDomain(value) {
  if (typeof value !== 'string' || value.length === 0 || value.length > MAX_DOMAIN_LENGTH) return false;
  const labels = value.split('.');
  if (labels.length < 2) return false;
  if (labels.every(label => DIGITS_ONLY.test(label))) return false; // raw IPv4
  return labels.every(label => (
    label.length > 0 &&
    label.length <= MAX_LABEL_LENGTH &&
    LABEL_CHARS.test(label) &&
    !label.startsWith('-') &&
    !label.endsWith('-')
  ));
}

/**
 * Parse and validate the serialized policy from the sidecar environment.
 * Throws on any malformed policy so the sidecar fails at startup rather than
 * discovering an unusable policy on the first request.
 *
 * @param {string|undefined|null} raw
 * @returns {{ enabled: boolean, mode: 'allow'|'block'|null, domains: string[], maxUses?: number }|null}
 */
function parseClaudeHostedWebPolicy(raw) {
  if (raw === undefined || raw === null || String(raw).trim() === '') return null;

  let parsed;
  try {
    parsed = JSON.parse(String(raw));
  } catch (err) {
    throw new Error(`AWF_CLAUDE_HOSTED_WEB_POLICY is not valid JSON: ${err.message}`);
  }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    throw new Error('AWF_CLAUDE_HOSTED_WEB_POLICY must be a JSON object');
  }
  if (typeof parsed.enabled !== 'boolean') {
    throw new Error('AWF_CLAUDE_HOSTED_WEB_POLICY.enabled must be a boolean');
  }

  if (!parsed.enabled) {
    return { enabled: false, mode: null, domains: [] };
  }

  if (parsed.mode !== 'allow' && parsed.mode !== 'block') {
    throw new Error('AWF_CLAUDE_HOSTED_WEB_POLICY.mode must be "allow" or "block" when enabled');
  }
  if (!Array.isArray(parsed.domains) || parsed.domains.length === 0) {
    throw new Error('AWF_CLAUDE_HOSTED_WEB_POLICY.domains must be a non-empty array when enabled');
  }
  const domains = [];
  for (const domain of parsed.domains) {
    if (!isValidDomain(domain)) {
      throw new Error(`AWF_CLAUDE_HOSTED_WEB_POLICY.domains contains an invalid domain: ${JSON.stringify(domain)}`);
    }
    if (!domains.includes(domain)) domains.push(domain);
  }

  const policy = { enabled: true, mode: parsed.mode, domains };

  if (parsed.maxUses !== undefined) {
    if (!Number.isInteger(parsed.maxUses) || parsed.maxUses < 1) {
      throw new Error('AWF_CLAUDE_HOSTED_WEB_POLICY.maxUses must be a positive integer');
    }
    policy.maxUses = parsed.maxUses;
  }

  return policy;
}

/**
 * Validate a request-supplied domain filter array.
 *
 * @param {unknown} value
 * @param {string} field - `allowed_domains` or `blocked_domains`
 * @returns {string[]}
 */
function readRequestDomains(value, field) {
  if (!Array.isArray(value) || value.length === 0) {
    throw new ClaudeHostedWebPolicyError(
      'claude_hosted_web_tool_invalid',
      `Hosted web tool "${field}" must be a non-empty array of domains.`,
      400,
    );
  }
  const domains = [];
  for (const entry of value) {
    const normalized = typeof entry === 'string' ? entry.trim().toLowerCase() : entry;
    if (!isValidDomain(normalized)) {
      throw new ClaudeHostedWebPolicyError(
        'claude_hosted_web_domain_invalid',
        `Hosted web tool "${field}" contains an invalid domain. Use lowercase DNS hostnames with at least two labels.`,
        400,
      );
    }
    if (!domains.includes(normalized)) domains.push(normalized);
  }
  return domains;
}

function hasField(tool, field) {
  return Object.prototype.hasOwnProperty.call(tool, field) && tool[field] !== undefined;
}

function resolveMaxUses(policy, tool) {
  if (!hasField(tool, 'max_uses')) return policy.maxUses;
  const requested = tool.max_uses;
  if (!Number.isInteger(requested) || requested < 1) {
    throw new ClaudeHostedWebPolicyError(
      'claude_hosted_web_max_uses_invalid',
      'Hosted web tool "max_uses" must be a positive integer.',
      400,
    );
  }
  return policy.maxUses === undefined ? requested : Math.min(policy.maxUses, requested);
}

/**
 * Compute the effective, policy-conformant replacement for one hosted web tool.
 *
 * @param {object} tool - Request tool definition
 * @param {object} policy - Normalized policy
 * @returns {object} New tool definition carrying the enforced policy
 */
function enforceToolPolicy(tool, policy) {
  // An explicitly present filter — even `null` — counts as request-supplied so
  // a malformed value is rejected rather than silently treated as "omitted".
  const hasAllowed = hasField(tool, 'allowed_domains');
  const hasBlocked = hasField(tool, 'blocked_domains');

  if (hasAllowed && hasBlocked) {
    throw new ClaudeHostedWebPolicyError(
      'claude_hosted_web_policy_conflict',
      'Hosted web tool declares both "allowed_domains" and "blocked_domains"; Anthropic permits only one.',
    );
  }

  const result = { ...tool };
  delete result.allowed_domains;
  delete result.blocked_domains;

  if (policy.mode === 'allow') {
    if (hasBlocked) {
      throw new ClaudeHostedWebPolicyError(
        'claude_hosted_web_policy_conflict',
        'Hosted web tool declares "blocked_domains" but AWF enforces an allowed-domain policy; ' +
          'Anthropic cannot represent both restrictions.',
      );
    }
    let effective = policy.domains;
    if (hasAllowed) {
      const requested = readRequestDomains(tool.allowed_domains, 'allowed_domains');
      effective = policy.domains.filter((domain) => requested.includes(domain));
      if (effective.length === 0) {
        throw new ClaudeHostedWebPolicyError(
          'claude_hosted_web_empty_intersection',
          'Hosted web tool "allowed_domains" has no overlap with the AWF-configured allowed domains.',
        );
      }
    }
    result.allowed_domains = effective;
  } else {
    if (hasAllowed) {
      throw new ClaudeHostedWebPolicyError(
        'claude_hosted_web_policy_conflict',
        'Hosted web tool declares "allowed_domains" but AWF enforces a blocked-domain policy; ' +
          'Anthropic cannot represent both restrictions.',
      );
    }
    let effective = policy.domains;
    if (hasBlocked) {
      const requested = readRequestDomains(tool.blocked_domains, 'blocked_domains');
      effective = [...policy.domains];
      for (const domain of requested) {
        if (!effective.includes(domain)) effective.push(domain);
      }
    }
    result.blocked_domains = effective;
  }

  const maxUses = resolveMaxUses(policy, tool);
  if (maxUses === undefined) {
    delete result.max_uses;
  } else {
    result.max_uses = maxUses;
  }

  return result;
}

/**
 * Apply the policy to a parsed Anthropic Messages body.
 *
 * Requests without a matching hosted web tool are returned unchanged (`null`),
 * so an ordinary Messages request — including one sent to a custom
 * Anthropic-compatible endpoint that implements no server tools — is never
 * mutated by this policy.
 *
 * @param {object} body - Parsed request body
 * @param {object} policy - Normalized policy
 * @returns {object|null} New body, or null when nothing matched
 */
function applyClaudeHostedWebPolicy(body, policy) {
  if (!body || !Array.isArray(body.tools)) return null;

  let matched = false;
  const tools = body.tools.map((tool) => {
    const type = tool && typeof tool === 'object' ? tool.type : undefined;
    if (!isHostedWebToolCandidate(type)) return tool;

    matched = true;

    if (!policy.enabled) {
      throw new ClaudeHostedWebPolicyError(
        'claude_hosted_web_disabled',
        'Claude hosted web search/fetch tools are disabled by AWF policy (apiProxy.hostedWeb.claude.enabled: false).',
      );
    }
    if (!isHostedWebToolType(type)) {
      throw new ClaudeHostedWebPolicyError(
        'claude_hosted_web_tool_unrecognized',
        'Unrecognized Claude hosted web tool version; AWF cannot prove the domain policy applies to it.',
        400,
      );
    }
    return enforceToolPolicy(tool, policy);
  });

  if (!matched) return null;
  return { ...body, tools };
}

/**
 * Build the hosted-web body transform for the Anthropic adapter.
 *
 * Returns `null` when no policy is configured (fast path: no-op), preserving
 * the pre-existing pass-through behaviour.
 *
 * @param {object|null} policy - Normalized policy from {@link parseClaudeHostedWebPolicy}
 * @returns {((body: Buffer) => Buffer|null)|null}
 */
function makeClaudeHostedWebTransform(policy) {
  if (!policy) return null;

  return (bodyBuffer) => {
    let parsed;
    try {
      parsed = JSON.parse(bodyBuffer.toString('utf8'));
    } catch {
      return null; // Not JSON — no hosted tool definition can be present
    }
    const updated = applyClaudeHostedWebPolicy(parsed, policy);
    if (updated === null) return null;

    const newBuffer = Buffer.from(JSON.stringify(updated), 'utf8');
    return newBuffer.equals(bodyBuffer) ? null : newBuffer;
  };
}

module.exports = {
  ClaudeHostedWebPolicyError,
  isHostedWebToolType,
  isHostedWebToolCandidate,
  parseClaudeHostedWebPolicy,
  applyClaudeHostedWebPolicy,
  makeClaudeHostedWebTransform,
};
