#!/usr/bin/env node
// Per-component Docker build contexts cannot COPY a shared parent directory.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const root = path.resolve(__dirname, '../..');
function extractDistrustedSpkis(source) {
  const sourceFile = ts.createSourceFile(
    'tls-trust-policy.ts',
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  if (sourceFile.parseDiagnostics.length > 0) {
    throw new Error('Unable to parse canonical TLS trust policy');
  }
  const declaration = sourceFile.statements
    .filter(ts.isVariableStatement)
    .flatMap(statement => statement.declarationList.declarations)
    .find(item => ts.isIdentifier(item.name) && item.name.text === 'distrustedSpkis');
  const initializer = declaration && declaration.initializer;
  if (!initializer || !ts.isNewExpression(initializer) || !ts.isIdentifier(initializer.expression)
      || initializer.expression.text !== 'Set' || initializer.arguments?.length !== 1
      || !ts.isArrayLiteralExpression(initializer.arguments[0])) {
    throw new Error('Canonical TLS trust policy must declare distrustedSpkis as a Set of string literals');
  }
  const keys = initializer.arguments[0].elements.map(element => (
    ts.isStringLiteral(element) ? element.text : ''
  ));
  if (keys.length === 0 || keys.some(key => !/^[a-f0-9]{64}$/.test(key)) || new Set(keys).size !== keys.length) {
    throw new Error('Canonical TLS trust policy contains missing, invalid, or duplicate SPKI hashes');
  }
  return keys;
}

function generate() {
  const source = fs.readFileSync(path.join(root, 'src/tls-trust-policy.ts'), 'utf8');
  const js = '// Generated by scripts/security/generate-trust-policy.cjs; do not edit.\n'
    + ts.transpileModule(source, {
      compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true },
    }).outputText;
  const hashes = `${extractDistrustedSpkis(source).join('\n')}\n`;
  const files = {
    'node-trust.cjs': js,
    'distrusted-spki.txt': hashes,
    'filter-ca-store.sh': fs.readFileSync(path.join(__dirname, 'filter-ca-store.sh'), 'utf8'),
    'install-system-trust.sh': fs.readFileSync(path.join(__dirname, 'install-system-trust.sh'), 'utf8'),
    'install-node-trust.sh': fs.readFileSync(path.join(__dirname, 'install-node-trust.sh'), 'utf8'),
  };
  let mismatched = false;
  for (const component of ['agent', 'api-proxy', 'cli-proxy', 'squid', 'build-tools', 'gh-aw-node', 'router', 'dind-ubuntu', 'trust']) {
    const dir = path.join(root, 'containers', component, ...(component === 'trust' ? [] : ['trust']));
    for (const [name, content] of Object.entries(files)) {
      const dest = path.join(dir, name);
      if (['squid', 'router', 'build-tools'].includes(component)
          && ['node-trust.cjs', 'install-node-trust.sh'].includes(name)) {
        if (!process.argv.includes('--check') && fs.existsSync(dest)) fs.unlinkSync(dest);
        continue;
      }
      if (process.argv.includes('--check')) {
        if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== content) {
          console.error(`Out-of-sync trust policy: ${path.relative(root, dest)}`);
          mismatched = true;
        }
      } else {
        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(dest, content);
      }
    }
  }
  if (mismatched) process.exitCode = 1;
}

if (require.main === module) generate();

module.exports = { extractDistrustedSpkis };
