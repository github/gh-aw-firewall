import { execFile } from 'child_process';
import { promises as fs } from 'fs';
import * as os from 'os';
import * as path from 'path';
import { promisify } from 'util';
import { buildNvxGuestRunScript, testHelpers } from './guest-entrypoint';

const execFileAsync = promisify(execFile);

describe('buildNvxGuestRunScript', () => {
  it('exports the per-run environment in sorted order before running the command', () => {
    const script = buildNvxGuestRunScript({
      environment: { HTTPS_PROXY: 'http://172.31.0.10:3128', AWF_RUNTIME: 'nvx' },
      workingDirectory: '/workspace',
      command: 'echo hello',
    });

    expect(script.split('\n')).toEqual([
      '#!/bin/sh',
      '# Generated by AWF for a single NVX one-shot microVM run. Do not edit.',
      'set -e',
      "if [ -e '/tmp/awf-home' ] || [ -L '/tmp/awf-home' ]; then",
      '  echo "NVX writable guest home already exists" >&2',
      '  exit 1',
      'fi',
      "mkdir -m 0700 '/tmp/awf-home'",
      "if [ -d '/home/awf' ]; then",
      "  cp -a '/home/awf/.' '/tmp/awf-home'",
      "  chmod -R u+rwX,go-rwx '/tmp/awf-home'",
      'fi',
      "export AWF_RUNTIME='nvx'",
      "export HTTPS_PROXY='http://172.31.0.10:3128'",
      "cd '/workspace'",
      "exec /bin/sh -c 'echo hello'",
      '',
    ]);
  });

  it('carries multi-word agent commands that a whitespace-free nvx_arg token cannot', () => {
    const script = buildNvxGuestRunScript({
      environment: {},
      workingDirectory: '/workspace/packages/app',
      command: 'copilot --allow-all-tools -p "fix the build"',
    });

    expect(script).toContain("cd '/workspace/packages/app'");
    expect(script).toContain(
      `exec /bin/sh -c 'copilot --allow-all-tools -p "fix the build"'`,
    );
  });

  it('escapes embedded single quotes with POSIX quote splicing', () => {
    const script = buildNvxGuestRunScript({
      environment: { MESSAGE: "it's fine" },
      workingDirectory: '/workspace',
      command: "echo 'done'",
    });

    expect(script).toContain(`export MESSAGE='it'\\''s fine'`);
    expect(script).toContain(`exec /bin/sh -c 'echo '\\''done'\\'''`);
  });

  it('rejects environment variable names that are not shell-safe', () => {
    expect(() => buildNvxGuestRunScript({
      environment: { 'BAD;NAME': 'x' },
      workingDirectory: '/workspace',
      command: 'true',
    })).toThrow(/Unsafe NVX guest environment variable name/);
  });

  it('rejects environment values containing NUL', () => {
    expect(() => buildNvxGuestRunScript({
      environment: { TOKEN: 'a\0b' },
      workingDirectory: '/workspace',
      command: 'true',
    })).toThrow(/must not contain NUL/);
  });

  it('rejects a relative working directory and an empty command', () => {
    expect(() => buildNvxGuestRunScript({
      environment: {},
      workingDirectory: 'workspace',
      command: 'true',
    })).toThrow(/must be absolute/);
    expect(() => buildNvxGuestRunScript({
      environment: {},
      workingDirectory: '/workspace',
      command: '   ',
    })).toThrow(/non-empty agent command/);
  });

  it('copies a read-only seed into an isolated writable home without modifying it', async () => {
    const root = await fs.mkdtemp(path.join(os.tmpdir(), 'awf-nvx-home-'));
    const seed = path.join(root, 'seed');
    const home = path.join(root, 'scratch', 'home');
    const sourceCache = path.join(seed, '.cache', 'copilot');
    await fs.mkdir(sourceCache, { recursive: true });
    await fs.mkdir(path.dirname(home));
    await fs.writeFile(path.join(sourceCache, 'state'), 'seed-state');
    await fs.chmod(path.join(sourceCache, 'state'), 0o444);
    await fs.chmod(sourceCache, 0o555);
    try {
      const setup = testHelpers.buildGuestHomeSetupLines(home, seed);
      const script = [
        '#!/bin/sh',
        'set -e',
        ...setup,
        `mkdir -p '${home}/.cache/copilot/pkg/linux-x64'`,
        `printf written > '${home}/.cache/copilot/pkg/linux-x64/proof'`,
      ].join('\n');
      await execFileAsync('/bin/sh', ['-c', script]);

      await expect(fs.readFile(
        path.join(home, '.cache/copilot/pkg/linux-x64/proof'),
        'utf8',
      )).resolves.toBe('written');
      await expect(fs.readFile(path.join(sourceCache, 'state'), 'utf8'))
        .resolves.toBe('seed-state');
      await expect(fs.lstat(path.join(sourceCache, 'pkg')))
        .rejects.toMatchObject({ code: 'ENOENT' });
      expect((await fs.stat(home)).mode & 0o777).toBe(0o700);
    } finally {
      await fs.chmod(sourceCache, 0o755);
      await fs.rm(root, { recursive: true, force: true });
    }
  });

  it('fails closed instead of reusing a pre-existing writable-home path', async () => {
    const root = await fs.mkdtemp(path.join(os.tmpdir(), 'awf-nvx-home-'));
    const home = path.join(root, 'home');
    const seed = path.join(root, 'seed');
    await fs.mkdir(home);
    await fs.mkdir(seed);
    try {
      const script = [
        '#!/bin/sh',
        'set -e',
        ...testHelpers.buildGuestHomeSetupLines(home, seed),
      ].join('\n');
      await expect(execFileAsync('/bin/sh', ['-c', script])).rejects.toMatchObject({
        code: 1,
      });
    } finally {
      await fs.rm(root, { recursive: true, force: true });
    }
  });
});
