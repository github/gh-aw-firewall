import type { SquidConfig } from '../types';
import { parseDomainConfig } from './domain-acl';
import { generateUpstreamProxySection } from './upstream-proxy';
import { generateAclSections } from './acl-generator';
import { generateAccessRules } from './access-rules';
import { buildConfigSections } from './config-sections';
import { validateApiProxyIp, validateCliProxyIp } from './validation';
import { generateApiProxyUpstreamSection, generateApiProxyBrokerSpliceSection } from './api-proxy-upstreams';
import { buildLoggingSection } from './log-sections';
import { buildOtlpAclSections } from './otlp-acl';
import { buildCliProxyAclSections } from './cli-proxy-acl';
import { RUNTIME_TIMEOUTS } from './runtime-timeouts';

/**
 * Generates Squid proxy configuration with domain whitelisting and optional blocklisting
 *
 * Supports both plain domains and wildcard patterns:
 * - Plain domains use dstdomain ACL (efficient, fast matching)
 * - Wildcard patterns use dstdom_regex ACL (regex matching)
 *
 * Blocked domains take precedence over allowed domains.
 *
 * Supports protocol-specific domain restrictions:
 * - http://domain.com  -> allow only HTTP traffic
 * - https://domain.com -> allow only HTTPS traffic
 * - domain.com         -> allow both HTTP and HTTPS (default)
 *
 * When sslBump is enabled, adds SSL Bump configuration for HTTPS inspection.
 *
 * @example
 * // Plain domain: github.com -> acl allowed_domains dstdomain .github.com
 * // Wildcard: *.github.com -> acl allowed_domains_regex dstdom_regex -i ^.*\.github\.com$
 * // HTTP only: http://api.example.com -> separate ACL with !CONNECT rule
 * // Blocked: internal.example.com -> acl blocked_domains dstdomain .internal.example.com
 */
export function generateSquidConfig(config: SquidConfig): string {
  const { domains, blockedDomains, sslBump, upstreamProxy, apiProxyIp, otlpEndpoints, cliProxyIp } = config;

  validateApiProxyIp(apiProxyIp);
  validateCliProxyIp(cliProxyIp);

  const { domainsByProto, patternsByProto } = parseDomainConfig(domains);
  const loggingSection = buildLoggingSection(config);
  const { aclLines, blockedDomainConfig } = generateAclSections(domainsByProto, patternsByProto, blockedDomains);
  const { accessRulesSection, denyRule } = generateAccessRules(
    domainsByProto,
    patternsByProto,
    blockedDomainConfig.accessRules
  );

  const allAclLines = [...blockedDomainConfig.aclLines];
  if (blockedDomainConfig.aclLines.length > 0 && aclLines.length > 0) {
    allAclLines.push('');
  }
  allAclLines.push(...aclLines);
  const { aclLines: otlpAclLines, accessRules: otlpAccessRules } = buildOtlpAclSections(otlpEndpoints);
  allAclLines.push(...otlpAclLines);

  const aclSection = allAclLines.length > 0 ? allAclLines.join('\n') : '# No domains configured';
  const {
    dlpAclSection,
    dlpAccessSection,
    portConfig,
    sslBumpSection,
    sslBumpUrlAccessSection,
    portAclsAndRules,
    apiProxySection,
    allowedIpSection,
    dnsSection,
    topologyPeersSection,
  } = buildConfigSections({
    ...config,
    domainsByProto,
    patternsByProto,
    brokerTlsSection: generateApiProxyBrokerSpliceSection(config),
  });
  const effectiveAccessRules = [accessRulesSection.trimEnd(), otlpAccessRules].filter(Boolean).join('\n') + '\n';
  const { aclSection: cliProxyAclSection, accessSection: cliProxyAccessSection } = buildCliProxyAclSections(cliProxyIp);

  const apiProxyUpstreamSection = generateApiProxyUpstreamSection(config, blockedDomainConfig.accessRules);

  return `# Squid configuration for egress traffic control
# Generated by awf
${sslBump ? '\n# SSL Bump mode enabled - HTTPS traffic will be intercepted for URL inspection' : ''}

# Disable pinger (ICMP) - requires NET_RAW capability which we don't have for security
pinger_enable off

# PID file location - use proxy-owned directory since container runs as non-root
pid_filename /var/run/squid/squid.pid

${loggingSection}

${aclSection}
${cliProxyAclSection}
${dlpAclSection}
# Port configuration
${portConfig}
${sslBumpSection}

# Network ACLs
acl localnet src 10.0.0.0/8
acl localnet src 172.16.0.0/12
acl localnet src 192.168.0.0/16
acl localnet src fc00::/7
acl localnet src fe80::/10

${topologyPeersSection}${apiProxyUpstreamSection}${portAclsAndRules}
${apiProxySection}
${allowedIpSection}# Deny CONNECT to raw IP addresses (IPv4 and IPv6)
# Prevents bypassing domain-based filtering via direct IP connections
acl dst_ipv4 dstdom_regex ^[0-9]+\\.[0-9]+\\.[0-9]+\\.[0-9]+$
acl dst_ipv6 dstdom_regex ^\\[?[0-9a-fA-F:]+\\]?$
http_access deny dst_ipv4
http_access deny dst_ipv6
${dlpAccessSection}
${sslBumpUrlAccessSection}
${effectiveAccessRules}${cliProxyAccessSection}# Deny requests to unknown domains (not in allow-list)
# This applies to all sources including localnet
${denyRule}

# Allow from trusted sources (after domain filtering)
http_access allow localnet
http_access allow localhost

# Deny everything else
http_access deny all

# Disable caching
cache deny all

# DNS settings - Squid resolves all domains for HTTP/HTTPS traffic
${dnsSection}
${upstreamProxy ? '\n' + generateUpstreamProxySection(upstreamProxy) : ''}
# Forwarded headers
forwarded_for delete
via off

# Error page customization
error_directory /usr/share/squid/errors/en

# Memory and file descriptor limits
cache_mem 64 MB
maximum_object_size 0 KB

${RUNTIME_TIMEOUTS}`;
}
